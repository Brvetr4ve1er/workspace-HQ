// Cosmos space — the paste for tools/fake-preload.js.
//
// The fake preload is sandboxed: it cannot require files (see the MONEY note in fake-preload.js). So the invented library is
// PASTED into it as source, between markers, and a test keeps the pasted copy equal to the generator (drift fails the test, like a
// golden). Two blocks, because they sit in two places:
//
//   fixture  top level, beside the MONEY const:      const fakeCosmos = <the source of fakeCosmos in cosmos-fixture.mjs>;
//   rows     inside createFake(), after the DLV block and BEFORE `const SPEC`: const COSMOS = (() => { ... })();
//            SPEC then spreads `...COSMOS.rows,` and control.reset() calls `COSMOS.reset()`.
//
// Usage:  node tools/cosmos-fixture-paste.mjs            print both blocks
//         node tools/cosmos-fixture-paste.mjs --write    rewrite fake-preload.js between its markers (they must already be there)
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { fakeCosmos } from './cosmos-fixture.mjs';

export const MARK = Object.freeze({
  fixture: Object.freeze({ begin: '// BEGIN cosmos-fixture (generated by tools/cosmos-fixture-paste.mjs; do not edit between the markers)', end: '// END cosmos-fixture' }),
  rows: Object.freeze({ begin: '  // BEGIN cosmos-rows (generated by tools/cosmos-fixture-paste.mjs; do not edit between the markers)', end: '  // END cosmos-rows' }),
});

/** The hq.cosmos method paths the rows answer: the same set dashboard/preload.js exposes (fake-preload.test.mjs checks the real one). */
export const COSMOS_METHODS = Object.freeze(['cosmos.read', 'cosmos.apply', 'cosmos.pickFolder', 'cosmos.index', 'cosmos.cancelIndex', 'cosmos.trash', 'cosmos.reveal', 'cosmos.importFiles', 'cosmos.importFromLocal', 'cosmos.pathForFile', 'cosmos.onProgress']);

/** Block 1: the generator as a top-level const (Function.prototype.toString of fakeCosmos, which is self-contained). */
export function fixtureBlock() {
  return [MARK.fixture.begin, '// Placeholder library for the Cosmos space: 40 works by default, sessionStorage "hqFake:cosmosCount" asks for more (readable copy: tools/cosmos-fixture.mjs).',
    'const fakeCosmos = ' + fakeCosmos.toString() + ';', MARK.fixture.end].join('\n');
}

/**
 * Block 2: the rows (inside createFake, where `storage` and `fakeCosmos` are in scope).
 *   cosmos.read          fakeCosmos({count: N}), N = Number(sessionStorage 'hqFake:cosmosCount') if set, else 40; the curation is the
 *                        copy cosmos.apply has been editing
 *   cosmos.apply         favorite / hide / tags / title round trip -> { view: { curation: <copy> }, note: 'saved' }; import-replace saves
 *                        nothing and answers the same; any other type is refused like main refuses an unknown intent
 *   cosmos.index         true (the scenarios drive the progress with hqFake.emit)
 *   cosmos.trash         moves nothing but a file dropped in (rel 'imports:...'); the rest come back in failed[] like main
 *   cosmos.pathForFile   SYNCHRONOUS: '' for a bare call, a File-like's own `fakePath` otherwise (the row kind is { sync: fn })
 */
export function rowsBlock() {
  return [
    MARK.rows.begin,
    "  // Cosmos space: answers fakeCosmos({count}); count = sessionStorage 'hqFake:cosmosCount' if set, else 40 (the global button sweep walks every screen, so the default is small).",
    '  const COSMOS = (() => {',
    '    const LIBS = new Map();   // count -> the generated answer (made once)',
    '    let cur = null, curCount = -1;   // the curation cosmos.apply edits; hqFake.reset() puts it back',
    '    const countNow = () => {',
    '      try {',
    "        const raw = storage && storage.getItem('hqFake:cosmosCount');",
    "        const v = raw == null || raw === '' ? NaN : Number(raw);",
    '        return Number.isFinite(v) && v >= 0 ? Math.floor(v) : 40;',
    '      } catch (e) { return 40; }',
    '    };',
    '    const lib = (n) => { let l = LIBS.get(n); if (!l) { l = fakeCosmos({ count: n }); LIBS.set(n, l); } return l; };',
    '    const curation = (n) => { if (!cur || curCount !== n) { cur = JSON.parse(JSON.stringify(lib(n).curation)); curCount = n; } return cur; };',
    '    const copy = (n) => JSON.parse(JSON.stringify(curation(n)));',
    '    const read = () => { const n = countNow(); return Object.assign({}, lib(n), { curation: copy(n) }); };',
    "    const norm = (t) => String(t).toLowerCase().trim().replace(/\\s+/g, ' ');",
    '    const apply = (intent) => {',
    "      const i = intent && typeof intent === 'object' ? intent : {};",
    '      const n = countNow(), c = curation(n), w = lib(n).works.find((x) => x.id === i.id);',
    "      if (['favorite', 'hide', 'tags', 'title'].includes(i.type)) {",
    "        if (!w) return { error: 'No such element' };",
    "        if (i.type === 'favorite' || i.type === 'hide') {",
    "          const m = i.type === 'favorite' ? c.favorites : c.hidden;",
    '          if (i.on) m[i.id] = true; else delete m[i.id];',
    '        } else {',
    '          const o = c.overrides[i.id] || (c.overrides[i.id] = {});',
    "          if (i.type === 'title') { if (i.title == null || String(i.title).trim() === '') delete o.title; else o.title = String(i.title); }",
    '          else {',
    '            let tags = (Array.isArray(o.tags) ? o.tags : w.tags).slice();',
    '            for (const t of Array.isArray(i.add) ? i.add : []) { const x = norm(t); if (x && !tags.includes(x)) tags.push(x); }',
    '            const gone = (Array.isArray(i.remove) ? i.remove : []).map(norm);',
    '            tags = tags.filter((t) => !gone.includes(t));',
    '            o.tags = tags;',
    '          }',
    '          if (Object.keys(o).length === 0) delete c.overrides[i.id];',
    '        }',
    '      } else if (i.type !== \'import-replace\') return { error: \'The fake preload does not do \' + String(i.type) };',
    "      return { view: { curation: copy(n) }, note: 'saved' };",
    '    };',
    '    const trash = (ids) => {',
    '      const works = lib(countNow()).works, trashed = [], failed = [];',
    '      for (const id of Array.isArray(ids) ? ids : []) {',
    '        const w = works.find((x) => x.id === id);',
    "        if (w && String(w.rel).startsWith('imports:')) trashed.push(id); else failed.push({ id, message: 'Only a file dropped into Cosmos can be moved to the Recycle Bin from here' });",
    '      }',
    '      return { trashed, failed };',
    '    };',
    "    const report = () => ({ clusters: 3, favorites: 25, hidden: 15, overrides: 4, found: 40, missingIds: ['alpha-site-9999'], missingCount: 1, conflicts: 0, token: null, seeded: 0, skipped: [], note: 'Imported the placeholder backup' });",
    "    const pathForFile = (f) => (f && typeof f === 'object' && typeof f.fakePath === 'string' ? f.fakePath : '');",
    '    return {',
    '      reset: () => { cur = null; curCount = -1; },',
    '      rows: [',
    "        ['cosmos.read', read], ['cosmos.apply', apply], ['cosmos.pickFolder', () => null], ['cosmos.index', () => true], ['cosmos.cancelIndex', () => true],",
    "        ['cosmos.trash', trash], ['cosmos.reveal', () => true], ['cosmos.importFiles', (paths) => ({ imported: Array.isArray(paths) ? paths.length : 0, skipped: [] })],",
    "        ['cosmos.importFromLocal', report], ['cosmos.pathForFile', { sync: pathForFile }], ['cosmos.onProgress', 'on:hq:cosmos:index-progress'],",
    '      ],',
    '    };',
    '  })();',
    MARK.rows.end,
  ].join('\n');
}

/** Both blocks. */
export function buildBlocks() {
  return { fixture: fixtureBlock(), rows: rowsBlock() };
}

const norm = (s) => String(s).replace(/\r\n/g, '\n');

/** The text between a marker pair (markers included), or null when either is missing or they are out of order. */
export function extractBlock(source, mark) {
  const text = norm(source), a = text.indexOf(mark.begin), b = text.indexOf(mark.end);
  if (a < 0 || b < 0 || b < a) return null;
  return text.slice(a, b + mark.end.length);
}

/** `source` with the block between the markers replaced; null when the markers are not both there. */
export function replaceBlock(source, mark, block) {
  const text = norm(source), a = text.indexOf(mark.begin), b = text.indexOf(mark.end);
  if (a < 0 || b < 0 || b < a) return null;
  return text.slice(0, a) + block + text.slice(b + mark.end.length);
}

/** Rewrite fake-preload.js. Resolves { written, missing[] }; writes nothing when a marker pair is missing. */
export function writeInto(file) {
  const src = fs.readFileSync(file, 'utf8');
  const crlf = src.includes('\r\n');
  const blocks = buildBlocks();
  const missing = [];
  let out = src;
  for (const key of ['fixture', 'rows']) {
    const next = replaceBlock(out, MARK[key], blocks[key]);
    if (next === null) missing.push(key); else out = next;
  }
  if (missing.length) return { written: false, missing };
  fs.writeFileSync(file, crlf ? out.replace(/\n/g, '\r\n') : out);
  return { written: true, missing };
}

