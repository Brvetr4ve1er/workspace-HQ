// The Crew (Claude > Crew) - the paste for tools/fake-preload.js, the same convention as tools/cosmos-fixture-paste.mjs.
//
// The fake preload is sandboxed: it cannot require files. So the invented crew is PASTED into it as source, between markers, and a test
// keeps the pasted copy equal to the generator (drift fails the test, like a golden). Two blocks, because they sit in two places:
//
//   fixture  top level, after the console fixture:     const fakeCrew = <the source of fakeCrew in crew-fixture.mjs>;
//   rows     inside createFake(), after the cosmos rows and BEFORE `const SPEC`: const CREW = (() => { ... })();
//            SPEC then spreads `...CREW.rows,` (between sessionsBoard and delivery, as in dashboard/preload.js) and control.reset() calls `CREW.reset()`.
//
// Usage:  node tools/crew-fixture-paste.mjs            print both blocks
//         node tools/crew-fixture-paste.mjs --init     insert the two EMPTY marker pairs at their anchors (once; refuses when present)
//         node tools/crew-fixture-paste.mjs --write    rewrite fake-preload.js between its markers (they must already be there)
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { fakeCrew } from './crew-fixture.mjs';

export const MARK = Object.freeze({
  fixture: Object.freeze({ begin: '// BEGIN crew-fixture (generated by tools/crew-fixture-paste.mjs; do not edit between the markers)', end: '// END crew-fixture' }),
  rows: Object.freeze({ begin: '  // BEGIN crew-rows (generated by tools/crew-fixture-paste.mjs; do not edit between the markers)', end: '  // END crew-rows' }),
});

/** Where --init puts the marker pairs: a line of fake-preload.js that must occur exactly once. */
export const ANCHOR = Object.freeze({
  fixtureBefore: '// BEGIN security-fixture',   // the fixture block goes in front of this line
  rowsAfter: '  // END cosmos-rows',            // the rows block goes right after this line
});

export const CREW_METHODS = Object.freeze(['crew.read', 'crew.start']);
export const STORAGE_KEY = 'hqFake:crewCount';
export const DEFAULT_COUNT = 24;

/** Block 1: the generator as a top-level const (Function.prototype.toString of fakeCrew, which is self-contained). */
export function fixtureBlock() {
  return [MARK.fixture.begin, '// Placeholder skills for the Crew view: 24 by default, sessionStorage "' + STORAGE_KEY + '" asks for more (readable copy: tools/crew-fixture.mjs).',
    'const fakeCrew = ' + fakeCrew.toString() + ';', MARK.fixture.end].join('\n');
}

/**
 * Block 2: the rows (inside createFake, where `storage` and `fakeCrew` are in scope).
 *   crew.read    fakeCrew({count}), count = Number(sessionStorage 'hqFake:crewCount') if set, else 24
 *   crew.start   answers { ok: true } for an id the roster has and can start, main's own fixed words for any other
 */
export function rowsBlock() {
  return [
    MARK.rows.begin,
    "  // The Crew: answers fakeCrew({count}); count = sessionStorage 'hqFake:crewCount' if set, else 24 (the global button sweep walks every screen, so the default is small).",
    '  const CREW = (() => {',
    '    const cache = new Map();',
    '    const countNow = () => {',
    '      try {',
    "        const raw = storage && storage.getItem('hqFake:crewCount');",
    "        const v = raw == null || raw === '' ? NaN : Number(raw);",
    '        return Number.isFinite(v) && v >= 0 ? Math.floor(v) : 24;',
    '      } catch (e) { return 24; }',
    '    };',
    '    const lib = () => { const n = countNow(); let l = cache.get(n); if (!l) { l = fakeCrew({ count: n }); cache.set(n, l); } return l; };',
    '    return {',
    '      rows: [',
    "        ['crew.read', () => JSON.parse(JSON.stringify(lib()))],",
    "        ['crew.start', (id) => (typeof id === 'string' && lib().skills.some((s) => s.id === id && s.canStart) ? { ok: true } : { error: 'that skill is not in the crew' })],",
    '      ],',
    '      reset: () => { cache.clear(); },',
    '    };',
    '  })();',
    MARK.rows.end,
  ].join('\n');
}

/** Both blocks. */
export function buildBlocks() {
  return { fixture: fixtureBlock(), rows: rowsBlock() };
}

const norm = (s) => String(s).replace(/\r\n/g, '\n');

/** The text between a marker pair (markers included), or null when either is missing or they are out of order. */
export function extractBlock(source, mark) {
  const text = norm(source), a = text.indexOf(mark.begin), b = text.indexOf(mark.end);
  if (a < 0 || b < 0 || b < a) return null;
  return text.slice(a, b + mark.end.length);
}

/** `source` with the block between the markers replaced; null when the markers are not both there. */
export function replaceBlock(source, mark, block) {
  const text = norm(source), a = text.indexOf(mark.begin), b = text.indexOf(mark.end);
  if (a < 0 || b < 0 || b < a) return null;
  return text.slice(0, a) + block + text.slice(b + mark.end.length);
}

/** Insert the two empty marker pairs at their anchors (once). Resolves { written, why }. */
export function initInto(file) {
  const src = fs.readFileSync(file, 'utf8');
  const crlf = src.includes('\r\n');
  let text = norm(src);
  if (text.includes(MARK.fixture.begin) || text.includes(MARK.rows.begin)) return { written: false, why: 'the markers are already there' };
  const count = (s) => text.split(s).length - 1;
  if (count(ANCHOR.fixtureBefore) !== 1 || count(ANCHOR.rowsAfter) !== 1) return { written: false, why: 'an anchor line is missing or not unique' };
  text = text.replace(ANCHOR.fixtureBefore, MARK.fixture.begin + '\n' + MARK.fixture.end + '\n' + ANCHOR.fixtureBefore);
  text = text.replace(ANCHOR.rowsAfter, ANCHOR.rowsAfter + '\n' + MARK.rows.begin + '\n' + MARK.rows.end);
  fs.writeFileSync(file, crlf ? text.replace(/\n/g, '\r\n') : text);
  return { written: true, why: '' };
}

/** Rewrite fake-preload.js. Resolves { written, missing[] }; writes nothing when a marker pair is missing. */
export function writeInto(file) {
  const src = fs.readFileSync(file, 'utf8');
  const crlf = src.includes('\r\n');
  const blocks = buildBlocks();
  const missing = [];
  let out = src;
  for (const key of ['fixture', 'rows']) {
    const next = replaceBlock(out, MARK[key], blocks[key]);
    if (next === null) missing.push(key); else out = next;
  }
  if (missing.length) return { written: false, missing };
  fs.writeFileSync(file, crlf ? out.replace(/\n/g, '\r\n') : out);
  return { written: true, missing };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const file = new URL('./fake-preload.js', import.meta.url);
  if (process.argv.includes('--init')) {
    const r = initInto(file);
    if (!r.written) { console.error('[crew-fixture-paste] ' + r.why); process.exit(1); }
    console.log('[crew-fixture-paste] marker pairs inserted');
  } else if (process.argv.includes('--write')) {
    const r = writeInto(file);
    if (!r.written) { console.error('[crew-fixture-paste] fake-preload.js lacks the marker pair(s): ' + r.missing.join(', ') + ' - run --init first'); process.exit(1); }
    console.log('[crew-fixture-paste] fake-preload.js rewritten between its markers');
  } else {
    const b = buildBlocks();
    console.log(b.fixture + '\n\n' + b.rows);
  }
}
