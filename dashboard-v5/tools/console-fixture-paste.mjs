// Console layer (batch 7) -- the paste for tools/fake-preload.js, the same convention as tools/cosmos-fixture-paste.mjs.
//
// The fake preload is sandboxed: it cannot require files (see the MONEY note in fake-preload.js). So the invented project list is
// PASTED into it as source, between markers, and a test keeps the pasted copy equal to the generator (drift fails the test).
// Two blocks, because they sit in two places:
//
//   fixture  top level, just before the security fixture:  const fakeShelfProjects = <the source of fakeShelfProjects in console-fixture.mjs>;
//   control  inside createFake()'s `const control = {` literal:  shelfProjects(n), the data hook the gates read
//
// The hook is on hqFake (the control object), NOT on hq: window.hq must keep exactly the real preload's method set
// (fake-preload.test.mjs compares them). hqFake.shelfProjects() answers scan-shaped invented projects; the count is the argument,
// else sessionStorage 'hqFake:projectCount', else 83. The page puts them into the model (a scenario / selftest helper does that,
// see cdp-shelf.mjs PAGE.putProjects): fake-preload.js itself has no DATA of its own, index.html loads ../dashboard/data.js.
//
// Usage:  node tools/console-fixture-paste.mjs            print both blocks
//         node tools/console-fixture-paste.mjs --init     insert the two EMPTY marker pairs at their anchors (once; refuses when present)
//         node tools/console-fixture-paste.mjs --write    rewrite fake-preload.js between its markers (they must already be there)
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { fakeShelfProjects } from './console-fixture.mjs';

export const MARK = Object.freeze({
  fixture: Object.freeze({ begin: '// BEGIN console-fixture (generated by tools/console-fixture-paste.mjs; do not edit between the markers)', end: '// END console-fixture' }),
  control: Object.freeze({ begin: '    // BEGIN console-control (generated by tools/console-fixture-paste.mjs; do not edit between the markers)', end: '    // END console-control' }),
});

/** Where --init puts the marker pairs: a line of fake-preload.js that must occur exactly once. */
export const ANCHOR = Object.freeze({
  fixtureBefore: '// BEGIN security-fixture',   // the fixture block goes in front of this line
  controlAfter: '  const control = {',          // the control block goes right after this line
});

export const STORAGE_KEY = 'hqFake:projectCount';
export const DEFAULT_COUNT = 83;

/** Block 1: the generator as a top-level const (Function.prototype.toString of fakeShelfProjects, which is self-contained). */
export function fixtureBlock() {
  return [MARK.fixture.begin, '// Placeholder projects for the Console layer Shelf: 83 by default, sessionStorage "' + STORAGE_KEY + '" asks for another count (readable copy: tools/console-fixture.mjs).',
    'const fakeShelfProjects = ' + fakeShelfProjects.toString() + ';', MARK.fixture.end].join('\n');
}

/**
 * Block 2: one property of the control object (so it ends with a comma).
 *   hqFake.shelfProjects(n)  fakeShelfProjects({ count }): n when given, else Number(sessionStorage 'hqFake:projectCount') if it is a
 *                            number >= 0, else 83. Read per call: no reload is needed to change the size.
 */
export function controlBlock() {
  return [
    MARK.control.begin,
    "    // Console layer Shelf: the invented projects the gates put into the page's model (count = the argument, else sessionStorage 'hqFake:projectCount', else 83).",
    '    shelfProjects: (n) => {',
    '      let c = ' + DEFAULT_COUNT + ';',
    "      try { const raw = storage && storage.getItem('" + STORAGE_KEY + "'); const v = raw == null || raw === '' ? NaN : Number(raw); if (Number.isFinite(v) && v >= 0) c = Math.floor(v); } catch (e) { /* no storage: the default */ }",
    '      return fakeShelfProjects({ count: n == null ? c : n });',
    '    },',
    MARK.control.end,
  ].join('\n');
}

/** Both blocks. */
export function buildBlocks() {
  return { fixture: fixtureBlock(), control: controlBlock() };
}

const norm = (s) => String(s).replace(/\r\n/g, '\n');

/** The text between a marker pair (markers included), or null when either is missing or they are out of order. */
export function extractBlock(source, mark) {
  const text = norm(source), a = text.indexOf(mark.begin), b = text.indexOf(mark.end);
  if (a < 0 || b < 0 || b < a) return null;
  return text.slice(a, b + mark.end.length);
}

/** `source` with the block between the markers replaced; null when the markers are not both there. */
export function replaceBlock(source, mark, block) {
  const text = norm(source), a = text.indexOf(mark.begin), b = text.indexOf(mark.end);
  if (a < 0 || b < 0 || b < a) return null;
  return text.slice(0, a) + block + text.slice(b + mark.end.length);
}

const count = (text, needle) => text.split(needle).length - 1;

/**
 * `source` with the two EMPTY marker pairs inserted at their anchors. Returns { text } or { error }: an error when a pair is already
 * there, or an anchor is missing or not unique (nothing is changed then).
 */
export function insertMarkers(source) {
  const text = norm(source);
  if (text.includes(MARK.fixture.begin) || text.includes(MARK.control.begin)) return { error: 'the console markers are already in the file' };
  if (count(text, '\n' + ANCHOR.fixtureBefore) !== 1 && !text.startsWith(ANCHOR.fixtureBefore)) return { error: 'anchor not found exactly once: ' + ANCHOR.fixtureBefore };
  if (count(text, '\n' + ANCHOR.controlAfter + '\n') !== 1) return { error: 'anchor not found exactly once: ' + ANCHOR.controlAfter };
  let out = text.replace('\n' + ANCHOR.fixtureBefore, '\n' + MARK.fixture.begin + '\n' + MARK.fixture.end + '\n\n' + ANCHOR.fixtureBefore);
  out = out.replace('\n' + ANCHOR.controlAfter + '\n', '\n' + ANCHOR.controlAfter + '\n' + MARK.control.begin + '\n' + MARK.control.end + '\n');
  return { text: out };
}

/** Rewrite fake-preload.js. Resolves { written, missing[] }; writes nothing when a marker pair is missing. */
export function writeInto(file) {
  const src = fs.readFileSync(file, 'utf8');
  const crlf = src.includes('\r\n');
  const blocks = buildBlocks();
  const missing = [];
  let out = src;
  for (const key of ['fixture', 'control']) {
    const next = replaceBlock(out, MARK[key], blocks[key]);
    if (next === null) missing.push(key); else out = next;
  }
  if (missing.length) return { written: false, missing };
  fs.writeFileSync(file, crlf ? out.replace(/\n/g, '\r\n') : out);
  return { written: true, missing };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const file = new URL('./fake-preload.js', import.meta.url);
  if (process.argv.includes('--init')) {
    const src = fs.readFileSync(file, 'utf8'), r = insertMarkers(src);
    if (r.error) { console.error('[console-fixture-paste] ' + r.error); process.exit(1); }
    fs.writeFileSync(file, src.includes('\r\n') ? r.text.replace(/\n/g, '\r\n') : r.text);
    console.log('[console-fixture-paste] fake-preload.js has its marker pairs; now run with --write');
  } else if (process.argv.includes('--write')) {
    const r = writeInto(file);
    if (!r.written) { console.error('[console-fixture-paste] fake-preload.js lacks the marker pair(s): ' + r.missing.join(', ') + ' - run with --init first (see the header of this file)'); process.exit(1); }
    console.log('[console-fixture-paste] fake-preload.js rewritten between its markers');
  } else {
    const b = buildBlocks();
    console.log(b.fixture + '\n\n' + b.control);
  }
}
