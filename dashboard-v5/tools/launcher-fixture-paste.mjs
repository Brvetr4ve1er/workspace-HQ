// The Launcher (Settings > Launcher, Open workspace) - the paste for tools/fake-preload.js, the same convention as tools/crew-fixture-paste.mjs.
//
// The fake preload is sandboxed: it cannot require files. So the invented Launcher is PASTED into it as source, between markers, and a test
// keeps the pasted copy equal to the generator (drift fails the test, like a golden). Two blocks:
//
//   fixture  top level, in front of the security fixture:   const makeLauncherFake = <the source of makeLauncherFake in launcher-fixture.mjs>;
//   rows     inside createFake(), after `const devAllowed` and BEFORE `const SPEC`:   const LNCH = makeLauncherFake({ mode, record, devAllowed });
//            SPEC then spreads `...LNCH.rows,` and control.reset() calls `LNCH.reset()`.
//
// Usage:  node tools/launcher-fixture-paste.mjs            print both blocks
//         node tools/launcher-fixture-paste.mjs --write    rewrite fake-preload.js between its markers (they must already be there)
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { makeLauncherFake } from './launcher-fixture.mjs';

export const MARK = Object.freeze({
  fixture: Object.freeze({ begin: '// BEGIN launcher-fixture (generated by tools/launcher-fixture-paste.mjs; do not edit between the markers)', end: '// END launcher-fixture' }),
  rows: Object.freeze({ begin: '  // BEGIN launcher-rows (generated by tools/launcher-fixture-paste.mjs; do not edit between the markers)', end: '  // END launcher-rows' }),
});

export const LAUNCHER_METHODS = Object.freeze(['launcher.read', 'launcher.add', 'launcher.remove', 'launcher.setEditor', 'launcher.open', 'launcher.openWorkspace']);
export const STORAGE_KEY = 'hqFake:launcher';

/** Block 1: the generator as a top-level const (Function.prototype.toString of makeLauncherFake, which is self-contained). */
export function fixtureBlock() {
  return [MARK.fixture.begin, '// Placeholder Launcher entries and projects (readable copy: tools/launcher-fixture.mjs). sessionStorage "' + STORAGE_KEY + '" = locked | error | refuse picks a state.',
    'const makeLauncherFake = ' + makeLauncherFake.toString() + ';', MARK.fixture.end].join('\n');
}

/** Block 2: the rows (inside createFake, where `storage`, `record` and `devAllowed` are in scope). */
export function rowsBlock() {
  return [
    MARK.rows.begin,
    "  // The Launcher: INVENTED entries and the gate's own projects. sessionStorage 'hqFake:launcher' picks a state: 'locked' (the list cannot be kept), 'error' (the read fails), 'refuse' (every add is refused in main's words); anything else is the ready list.",
    "  const LNCH = makeLauncherFake({ mode: () => { try { return (storage && storage.getItem('" + STORAGE_KEY + "')) || ''; } catch (e) { return ''; } }, record, devAllowed });",
    MARK.rows.end,
  ].join('\n');
}

export function buildBlocks() { return { fixture: fixtureBlock(), rows: rowsBlock() }; }

const norm = (s) => String(s).replace(/\r\n/g, '\n');

/** The text between a marker pair (markers included), or null when either is missing or they are out of order. */
export function extractBlock(source, mark) {
  const text = norm(source), a = text.indexOf(mark.begin), b = text.indexOf(mark.end);
  if (a < 0 || b < 0 || b < a) return null;
  return text.slice(a, b + mark.end.length);
}

/** `source` with the block between the markers replaced; null when the markers are not both there. */
export function replaceBlock(source, mark, block) {
  const text = norm(source), a = text.indexOf(mark.begin), b = text.indexOf(mark.end);
  if (a < 0 || b < 0 || b < a) return null;
  return text.slice(0, a) + block + text.slice(b + mark.end.length);
}

/** Rewrite fake-preload.js. Resolves { written, missing[] }; writes nothing when a marker pair is missing. */
export function writeInto(file) {
  const src = fs.readFileSync(file, 'utf8');
  const crlf = src.includes('\r\n');
  const blocks = buildBlocks();
  const missing = [];
  let out = src;
  for (const key of ['fixture', 'rows']) {
    const next = replaceBlock(out, MARK[key], blocks[key]);
    if (next === null) missing.push(key); else out = next;
  }
  if (missing.length) return { written: false, missing };
  fs.writeFileSync(file, crlf ? out.replace(/\n/g, '\r\n') : out);
  return { written: true, missing };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const file = new URL('./fake-preload.js', import.meta.url);
  if (process.argv.includes('--write')) {
    const r = writeInto(file);
    if (!r.written) { console.error('[launcher-fixture-paste] fake-preload.js lacks the marker pair(s): ' + r.missing.join(', ')); process.exit(1); }
    console.log('[launcher-fixture-paste] fake-preload.js rewritten between its markers');
  } else {
    const b = buildBlocks();
    console.log(b.fixture + '\n\n' + b.rows);
  }
}
